#!/bin/bash
# The one way a vendored source changes (MODULAR_DESIGN §10). Each library
# lives in its own folder under Vendor/, with the release it came from in
# VERSION and its licence in LICENSE. Nothing there, and nothing generated
# from it, is edited by hand.
#
#   scripts/bump-vendor.sh cldr <release-tag>   pin CLDR's windowsZones at that release
#   scripts/bump-vendor.sh cldr                 regenerate the Swift table from what is pinned
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

# CLDR's windowsZones: each Windows zone key's IANA zone, the table ICU uses.
# DataSources' Windows time zone reads it (#565).
cldr() {
    local dir=Vendor/CLDR
    if [[ $# -gt 0 ]]; then
        local base="https://raw.githubusercontent.com/unicode-org/cldr/$1"
        mkdir -p "$dir"
        curl -fsSL "$base/common/supplemental/windowsZones.xml" -o "$dir/windowsZones.xml"
        curl -fsSL "$base/LICENSE" -o "$dir/LICENSE"
        echo "$1" > "$dir/VERSION"
    fi
    python3 - "$dir" Modules/DataSources/Sources/Internal/Time/WindowsZones+Table.swift <<'EOF'
import json, sys, xml.etree.ElementTree as ET

folder, out = sys.argv[1], sys.argv[2]
version = open(f"{folder}/VERSION").read().strip()
zones = {
    zone.get("other"): zone.get("type")
    for zone in ET.parse(f"{folder}/windowsZones.xml").iter("mapZone")
    if zone.get("territory") == "001"
}
rows = "\n".join(f"        {json.dumps(key)}: {json.dumps(zones[key])}," for key in sorted(zones))
open(out, "w").write(f"""// Generated by scripts/bump-vendor.sh from Vendor/CLDR/windowsZones.xml
// (CLDR {version}). Do not edit: run the script.

extension WindowsZones {{
    /// Each Windows zone key's IANA zone: CLDR's `windowsZones`, territory
    /// `001`, the mapping ICU uses.
    static let iana: [String: String] = [
{rows}
    ]
}}
""")
print(f"{out}: {len(zones)} zones from CLDR {version}")
EOF
}

case "${1:-}" in
    cldr) shift; cldr "$@" ;;
    *) echo "usage: $0 cldr [release-tag]" >&2; exit 64 ;;
esac
